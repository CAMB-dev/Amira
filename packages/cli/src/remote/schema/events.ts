import type { EventMap } from "@amira/api"
import {
  array,
  bool,
  number,
  object,
  record,
  type Schema,
  taggedUnion,
  text,
  union,
  enumeration as values,
} from "./base.ts"
import { formAction, uiRequest } from "./forms.ts"
import { budget, compaction } from "./frontend.ts"
import {
  assistantMessage,
  errorKind,
  modelRef,
  reasoning,
  serverTool,
  toolResult,
  usage,
  userMessage,
} from "./messages.ts"

const toolTraits = object({
  "readOnly?": bool,
  "writesFiles?": union(bool, values("paths")),
  "shell?": values("bash", "powershell"),
  "editor?": values("edit", "apply_patch"),
  "usesMutationHook?": bool,
  "artifactReader?": bool,
  "toolSearch?": bool,
  "interactive?": bool,
})
const group = object({
  id: text,
  name: text,
  parentSessionId: text,
  state: values("active", "ending", "ended"),
  limits: object({
    "maxConcurrent?": number,
    "maxAgents?": number,
    "budget?": budget,
    "maxTurnsPerAgent?": number,
  }),
  "compact?": bool,
  "status?": text,
  usage,
  tokens: number,
  agents: object({
    total: number,
    "paused?": number,
    queued: number,
    working: number,
    idle: number,
    ended: number,
  }),
  "outcomes?": object({ done: number, failed: number, stopped: number }),
  "endReason?": text,
  "exceeded?": bool,
})
const printOptions = { "details?": text, "markdown?": bool, "persist?": bool }

/** Exhaustive core envelopes, independent of legacy RPC's permissive newer-event fallback. */
export const coreEventData = {
  "session.start": object({
    reason: values("startup", "resume", "fork", "clear"),
    cwd: text,
    "title?": text,
    model: modelRef,
    "sessionFile?": text,
    "resume?": array(text),
    "contextTokens?": number,
    "contextWindow?": number,
  }),
  "workspace.changed": object({
    cwd: text,
    "repoRoot?": text,
    "branch?": text,
    "head?": text,
    "isWorktree?": bool,
    "dirty?": bool,
  }),
  "session.title": object({ title: text }),
  "session.end": object({ reason: values("exit", "error", "switch") }),
  "status.changed": object({
    status: values("idle", "working", "blocked", "error"),
    "reason?": text,
    "pending?": number,
  }),
  "turn.start": object({ prompt: userMessage, "sentAt?": number }),
  "turn.end": object({
    reason: values("done", "error", "aborted"),
    "error?": text,
    steps: number,
    "failure?": object({ kind: errorKind, summary: text, "hint?": text, "detail?": text }),
  }),
  "model.retry": object({
    attempt: number,
    maxRetries: number,
    delayMs: number,
    error: text,
    kind: errorKind,
    "status?": number,
  }),
  "turn.steer": union(
    object({ message: userMessage, state: values("queued", "injected", "dropped") }),
    object({ message: userMessage, state: values("promoted"), nextTurnId: text }),
  ),
  "message.start": object({ model: modelRef, "contextWindow?": number }),
  "message.stream": union(
    object({ kind: values("request"), "thinkingDisplay?": values("summarized", "omitted", "raw") }),
    object({ kind: values("contentStart", "thinkingStart", "thinkingEnd"), "index?": number }),
    object({ kind: values("end"), "outputTokens?": number }),
  ),
  "message.delta": union(
    object({ kind: values("text", "thinking"), text }),
    object({ kind: values("toolCall"), toolCallId: text, "index?": number, "name?": text, argsDelta: text }),
    object({ kind: values("serverTool"), block: serverTool }),
  ),
  "message.end": object({ message: assistantMessage }),
  "tool.execute.start": object({
    toolCallId: text,
    name: text,
    args: record({}),
    "traits?": toolTraits,
    "writtenPaths?": array(text),
  }),
  "tool.execute.update": object({ toolCallId: text, name: text, partial: toolResult }),
  "tool.execute.end": object({
    toolCallId: text,
    name: text,
    result: toolResult,
    durationMs: number,
    "waitedMs?": number,
    "traits?": toolTraits,
    "writtenPaths?": array(text),
    "rejected?": values("blocked", "unknownTool", "invalidArgs", "aborted"),
    "approval?": values("user", "rule"),
  }),
  "extension.loaded": object({ source: text }),
  "extension.error": object({ source: text, error: text }),
  "extension.notice": object({
    source: text,
    text,
    level: values("info", "success", "warning", "error"),
    ...printOptions,
  }),
  "ui.render": object({}),
  "events.lost": object({ dropped: number }),
  "ui.request": uiRequest,
  "ui.resolved": object({ requestId: text, cancelled: bool, "value?": union(text, bool) }),
  "ui.focus": object({ focused: bool }),
  "ui.progress": object({
    requestId: text,
    action: text,
    text,
    "form?": object({ result: formAction, errors: record(text) }),
  }),
  "ui.waiting": object({ pending: number, hidden: bool, change: values("opened", "resolved", "visibility") }),
  "model.changed": object({ from: modelRef, to: modelRef }),
  "thinking.changed": object({ "thinking?": reasoning }),
  "compact.start": object({
    reason: values("threshold", "manual", "overflow"),
    replacing: number,
    kept: number,
    "tokens?": number,
    "native?": bool,
  }),
  "compact.end": object({
    summary: text,
    replaced: number,
    kept: number,
    ...compaction,
    "usage?": usage,
    "usageIncomplete?": bool,
  }),
  "compact.failed": object({
    error: text,
    "blocked?": bool,
    "empty?": bool,
    "usage?": usage,
    "requested?": bool,
    "usageIncomplete?": bool,
  }),
  "command.output": object({
    command: text,
    text,
    level: values("info", "warning", "error"),
    ...printOptions,
  }),
  "subagent.start": object({
    childSessionId: text,
    "role?": text,
    "title?": text,
    "toolCallId?": text,
    prompt: text,
    model: modelRef,
    depth: number,
    cwd: text,
    context: values("fresh", "fork"),
    queued: bool,
    "persistent?": bool,
    "groupId?": text,
  }),
  "subagent.end": object({
    childSessionId: text,
    "toolCallId?": text,
    status: values("done", "error", "aborted"),
    "error?": text,
    "note?": text,
    "turns?": number,
    "undelivered?": number,
    usage,
    durationMs: number,
  }),
  "subagent.state": object({
    childSessionId: text,
    state: values("queued", "working", "idle", "paused"),
    turns: number,
  }),
  "group.start": object({ group }),
  "group.update": object({ group }),
  "group.end": object({ group }),
  "budget.update": object({ tokens: number, "costUsd?": number, "pricingUnknown?": bool, "limit?": budget }),
  "budget.exceeded": object({ tokens: number, "costUsd?": number, limit: budget }),
  "notice.retry": object({ attempt: number, attempts: number, delayMs: number, "error?": text }),
} satisfies Record<keyof EventMap, Schema>
export const coreEvent = taggedUnion(coreEventData, "type", "data", {
  seq: number,
  ts: number,
  sessionId: text,
  "parentSessionId?": text,
  "turnId?": text,
})
